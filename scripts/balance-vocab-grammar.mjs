#!/usr/bin/env node
// balance-vocab-grammar.mjs
// ---------------------------------------------------------------------------
// Two-pass rebalance for VOCAB + GRAMMAR (these have no `topic`/`passage`):
//
//   Pass 1 (length): for each question whose correct option is uniquely
//   the longest, pad the shortest distractor(s) with neutral qualifier
//   tails until the correct option is no longer the sole longest. Caps
//   at 3 pad attempts to avoid runaway strings on edge cases.
//
//   Pass 2 (letter): reorder options so A/B/C/D each occur ~25% of the
//   time per level (round-robin with per-level offset). Updates `answer`
//   index. References to letters in `ex` are remapped using the existing
//   helper logic from balance-answers.mjs.
//
// Usage:  node scripts/balance-vocab-grammar.mjs
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');

const FILES = [
  {
    label: 'VOCAB',
    srcPath: path.join(ROOT, 'src', 'vocab-data.js'),
    exportName: 'VOCAB',
    header: [
      '// JFLT Vocabulary Database — Balanced answer + length distribution',
      '// Generated by scripts/balance-vocab-grammar.mjs',
      '',
      'export const VOCAB = {',
    ].join('\n'),
  },
  {
    label: 'GRAMMAR',
    srcPath: path.join(ROOT, 'src', 'grammar-data.js'),
    exportName: 'GRAMMAR',
    header: [
      '// JFLT Grammar Database — Balanced answer + length distribution',
      '// Generated by scripts/balance-vocab-grammar.mjs',
      '',
      'export const GRAMMAR = {',
    ].join('\n'),
  },
];

const LEVEL_OFFSET = { 1: 0, 2: 1, 3: 2, 4: 3 };
const LETTERS = ['A', 'B', 'C', 'D'];

// Neutral qualifier tails cycled for padding. Designed to read plausibly
// at the end of definition-style noun phrases AND full-sentence options.
const PAD_TAILS = [
  ' in standard military usage',
  ' under normal operational conditions',
  ' as commonly understood in the field',
  ' according to standard doctrine',
  ' in the conventional sense of the term',
];

// ----- letter-reference remap (copied from balance-answers.mjs) -----
const VERB_TOKENS = [
  'is', 'are', 'was', 'were',
  'paraphrases', 'paraphrase',
  'reverses', 'reverse',
  'captures', 'capture',
  'reads', 'read',
  'matches', 'match',
  'maps', 'map',
  'identifies', 'identify',
  'fabricates', 'fabricate', 'fabricated',
  'misreads', 'misread',
  'contradicts', 'contradict',
  'inverts', 'invert',
  'uses', 'use',
  'introduces', 'introduce',
  'references', 'reference',
  'gets', 'get',
  'misses', 'miss',
  'adds', 'add',
  'states', 'state',
  'reflects', 'reflect',
  'distorts', 'distort',
  'oversimplifies',
  'sounds', 'looks',
  'represents',
  'mischaracterises', 'mischaracterizes',
  'narrows', 'narrow',
  'broadens', 'broaden',
  'means',
  'shows',
  'describes',
];
const VERB_GROUP = VERB_TOKENS.join('|');

function remapExplanation(ex, map) {
  if (!ex || typeof ex !== 'string') return { text: ex, warnings: [] };
  let text = ex;

  text = text.replace(/\b(option |Option |options |Options )([ABCD])\b/g,
    (_m, prefix, l) => `${prefix}__${l}__`);
  text = text.replace(/\b(Distractor |distractor |Distractors |distractors )([ABCD])\b/g,
    (_m, prefix, l) => `${prefix}__${l}__`);
  text = text.replace(/\b([ABCD]) and ([ABCD])\b/g,
    (_m, l1, l2) => `__${l1}__ and __${l2}__`);
  text = text.replace(/\b([ABCD]), ([ABCD])(?:, ([ABCD]))?(?:,? and ([ABCD]))?\b/g,
    (_m, l1, l2, l3, l4) => {
      let s = `__${l1}__, __${l2}__`;
      if (l3) s += `, __${l3}__`;
      if (l4) s += `, and __${l4}__`;
      return s;
    });
  const verbRe = new RegExp(`\\b([ABCD]) (${VERB_GROUP})\\b`, 'g');
  text = text.replace(verbRe, (_m, l, v) => `__${l}__ ${v}`);
  text = text.replace(/__([ABCD])__/g, (_m, l) => map[l] || l);

  const warnings = [];
  const bareRe = /(?<![A-Za-z])([ABCD])(?![A-Za-z])/g;
  let m;
  while ((m = bareRe.exec(text)) != null) {
    const start = Math.max(0, m.index - 25);
    const end = Math.min(text.length, m.index + 30);
    warnings.push({ letter: m[1], snippet: text.slice(start, end) });
  }
  return { text, warnings };
}

// ----- Pass 1: length balancing -----
function isUniquelyLongest(options, idx) {
  const lens = options.map(o => o.length);
  const max = Math.max(...lens);
  return lens[idx] === max && lens.filter(l => l === max).length === 1;
}

function padOptions(options, correctIdx, qIdx) {
  let opts = options.slice();
  let attempts = 0;
  let padCursor = qIdx % PAD_TAILS.length;
  while (isUniquelyLongest(opts, correctIdx) && attempts < 3) {
    // Find shortest distractor index
    let shortestIdx = -1;
    let shortestLen = Infinity;
    for (let i = 0; i < opts.length; i++) {
      if (i === correctIdx) continue;
      if (opts[i].length < shortestLen) {
        shortestLen = opts[i].length;
        shortestIdx = i;
      }
    }
    if (shortestIdx === -1) break;
    // Append a tail. Avoid appending the same tail to the same option twice.
    let tail = PAD_TAILS[padCursor % PAD_TAILS.length];
    padCursor++;
    if (opts[shortestIdx].endsWith(tail)) {
      tail = PAD_TAILS[padCursor % PAD_TAILS.length];
      padCursor++;
    }
    opts[shortestIdx] = opts[shortestIdx] + tail;
    attempts++;
  }
  return opts;
}

// ----- Pass 2: reorder for letter distribution -----
function reorderOptions(options, correctIdx, targetIdx) {
  if (correctIdx === targetIdx) {
    return { options: options.slice(), oldToNew: { 0: 0, 1: 1, 2: 2, 3: 3 } };
  }
  const correctOpt = options[correctIdx];
  const rest = options.filter((_, i) => i !== correctIdx);
  const newOpts = [];
  let restPtr = 0;
  for (let i = 0; i < 4; i++) {
    if (i === targetIdx) newOpts.push(correctOpt);
    else newOpts.push(rest[restPtr++]);
  }
  const oldToNew = {};
  oldToNew[correctIdx] = targetIdx;
  let writeIdx = 0;
  for (let oldIdx = 0; oldIdx < 4; oldIdx++) {
    if (oldIdx === correctIdx) continue;
    while (writeIdx === targetIdx) writeIdx++;
    oldToNew[oldIdx] = writeIdx;
    writeIdx++;
  }
  return { options: newOpts, oldToNew };
}

function formatQuestion(q) {
  const parts = [];
  parts.push(`question: ${JSON.stringify(q.question)}`);
  parts.push(`options: [${q.options.map(o => JSON.stringify(o)).join(', ')}]`);
  parts.push(`answer: ${q.answer}`);
  parts.push(`ex: ${JSON.stringify(q.ex)}`);
  return `    { ${parts.join(', ')} }`;
}

function distributionOf(dict) {
  const counts = { A: 0, B: 0, C: 0, D: 0 };
  for (const lvKey of Object.keys(dict)) {
    for (const q of dict[lvKey]) counts[LETTERS[q.answer]]++;
  }
  return counts;
}

function uniquelyLongestCount(dict) {
  let count = 0;
  let total = 0;
  for (const lvKey of Object.keys(dict)) {
    for (const q of dict[lvKey]) {
      total++;
      if (isUniquelyLongest(q.options, q.answer)) count++;
    }
  }
  return { count, total };
}

async function processFile(spec) {
  console.log(`\n========== ${spec.label} ==========`);
  const mod = await import(pathToFileURL(spec.srcPath).href + `?t=${Date.now()}`);
  const data = mod[spec.exportName];
  if (!data) throw new Error(`No export ${spec.exportName} in ${spec.srcPath}`);

  console.log('Before letters:', distributionOf(data));
  const beforeLen = uniquelyLongestCount(data);
  console.log(`Before uniquelyLongest: ${beforeLen.count}/${beforeLen.total} (${(beforeLen.count/beforeLen.total*100).toFixed(0)}%)`);

  const allWarnings = [];
  const balanced = {};

  for (const lvKey of Object.keys(data).sort()) {
    const lv = Number(lvKey);
    const questions = data[lvKey];
    const offset = LEVEL_OFFSET[lv] ?? 0;
    const out = [];
    for (let i = 0; i < questions.length; i++) {
      const q = questions[i];
      // Pass 1: length pad
      const paddedOpts = padOptions(q.options, q.answer, i);
      // Pass 2: reorder for letter
      const targetIdx = (offset + i) % 4;
      const { options: newOpts, oldToNew } = reorderOptions(
        paddedOpts, q.answer, targetIdx);
      const letterMap = {};
      for (const [oldIdx, newIdx] of Object.entries(oldToNew)) {
        letterMap[LETTERS[oldIdx]] = LETTERS[newIdx];
      }
      const { text: newEx, warnings } = remapExplanation(q.ex, letterMap);
      if (warnings.length > 0) {
        for (const w of warnings) {
          allWarnings.push({
            level: lv, qIdx: i,
            question: q.question.slice(0, 60),
            letter: w.letter, snippet: w.snippet, map: letterMap,
          });
        }
      }
      out.push({ ...q, options: newOpts, answer: targetIdx, ex: newEx });
    }
    balanced[lv] = out;
  }

  console.log('After  letters:', distributionOf(balanced));
  const afterLen = uniquelyLongestCount(balanced);
  console.log(`After  uniquelyLongest: ${afterLen.count}/${afterLen.total} (${(afterLen.count/afterLen.total*100).toFixed(0)}%)`);

  // Serialise
  const lines = [spec.header];
  for (const lvKey of Object.keys(balanced).sort()) {
    lines.push(`  ${lvKey}: [`);
    const qs = balanced[lvKey];
    lines.push(qs.map(formatQuestion).join(',\n'));
    lines.push('  ],');
  }
  lines.push('};');
  lines.push('');

  writeFileSync(spec.srcPath, lines.join('\n'), { encoding: 'utf8' });
  console.log(`Wrote ${spec.srcPath}`);
  return allWarnings;
}

const allWarnings = [];
for (const spec of FILES) {
  const w = await processFile(spec);
  allWarnings.push(...w.map(x => ({ ...x, file: spec.label })));
}

console.log('\n========== WARNINGS ==========');
if (allWarnings.length === 0) {
  console.log('None. All option-letter references remapped cleanly.');
} else {
  console.log(`${allWarnings.length} bare-letter reference(s) for manual review:`);
  for (const w of allWarnings.slice(0, 20)) {
    console.log(`  [${w.file} L${w.level} Q${w.qIdx}] ${w.question}`);
    console.log(`    '${w.letter}' near: …${w.snippet}…`);
  }
  if (allWarnings.length > 20) console.log(`  ... and ${allWarnings.length - 20} more`);
}
